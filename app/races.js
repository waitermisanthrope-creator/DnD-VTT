var customRaces = [];

function loadCustomRaces() {
  var saved = localStorage.getItem('dnd_custom_races');
  if (saved) {
    try { customRaces = JSON.parse(saved); } catch(e) { customRaces = []; }
  }
}

function saveCustomRaces() {
  localStorage.setItem('dnd_custom_races', JSON.stringify(customRaces));
}

function getAllRaces() {
  return DEFAULT_RACES.concat(customRaces);
}

