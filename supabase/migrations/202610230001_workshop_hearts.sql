create or replace function public.read_workshop_hearts(p_ids text[]) returns jsonb
language plpgsql security definer set search_path='' as $$
declare items jsonb;
begin
 if p_ids is null or cardinality(p_ids)>500 then raise exception 'Maximum 500 mod IDs' using errcode='22023';end if;
 if auth.uid() is not null then perform app_private.center_guard();end if;
 select coalesce(jsonb_agg(to_jsonb(t) order by t.id),'[]'::jsonb) into items from (
  select m.id,count(h.user_id) rating,coalesce(bool_or(h.user_id=auth.uid()),false) hearted
  from app_private.workshop_mods m left join app_private.workshop_hearts h on h.mod_id=m.id
  where m.active and m.id=any(p_ids) group by m.id
 )t;
 return jsonb_build_object('items',items,'authenticated',auth.uid() is not null);
end;$$;
create or replace function public.set_workshop_heart(p_id text,p_hearted boolean) returns jsonb
language plpgsql security definer set search_path='' as $$
declare total bigint;
begin
 perform app_private.center_guard();
 if p_hearted is null or p_id is null then raise exception 'Missing heart intent' using errcode='22023';end if;
 if not exists(select 1 from app_private.workshop_mods where id=p_id and active) then raise exception 'Unknown mod' using errcode='22023';end if;
 -- Serialize a mod's updates so the returned count includes this mutation.
 perform pg_advisory_xact_lock(hashtextextended(p_id,37));
 if p_hearted then
  insert into app_private.workshop_hearts(mod_id,user_id) values(p_id,auth.uid()) on conflict do nothing;
 else
  delete from app_private.workshop_hearts where mod_id=p_id and user_id=auth.uid();
 end if;
 select count(*) into total from app_private.workshop_hearts where mod_id=p_id;
 -- Explicit intent makes retrying a lost response safe; the UI implements the toggle.
 return jsonb_build_object('id',p_id,'rating',total,'hearted',p_hearted);
end;$$;
