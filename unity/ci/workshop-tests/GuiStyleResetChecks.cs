using System;
using System.IO;
using System.Linq;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
static class GuiStyleResetChecks
{
 public static string Source(string root)
 {
  var fields=Directory.GetFiles(Path.Combine(root,"unity/Assets/Vtt/Runtime"),"LegacySessionPanel*.cs").SelectMany(file=>CSharpSyntaxTree.ParseText(File.ReadAllText(file)).GetRoot().DescendantNodes().OfType<FieldDeclarationSyntax>()).Where(f=>f.Parent is ClassDeclarationSyntax c&&c.Identifier.Text=="LegacySessionPanel").SelectMany(f=>f.Declaration.Variables.Select(v=>(type:f.Declaration.Type.ToString(),name:v.Identifier.Text))).Where(f=>f.type=="GUIStyle"||f.type=="GUIStyle[]").OrderBy(f=>f.name,StringComparer.Ordinal).ToArray();
  return "// Generated by workshop-tests --generate-gui-style-cache. Do not hand edit.\nnamespace DndVtt.UnityPrototype\n{\n    public sealed partial class LegacySessionPanel\n    {\n        private void ResetGuiStyleCaches()\n        {\n"+string.Join("\n",fields.Select(f=>f.type=="GUIStyle[]"?"            System.Array.Clear("+f.name+",0,"+f.name+".Length);":"            "+f.name+"=null;"))+"\n        }\n    }\n}\n";
 }
 public static int Run(string root)
 {
  string path=Path.Combine(root,"unity/Assets/Vtt/Runtime/LegacySessionPanel.StyleCache.cs");
  if(!File.Exists(path)||File.ReadAllText(path)!=Source(root))throw new Exception("Destructive theme rebuild must reset every cached GUIStyle, including arrays, before releasing its shared backgrounds");return 1;
 }
 public static void Generate(string root)=>File.WriteAllText(Path.Combine(root,"unity/Assets/Vtt/Runtime/LegacySessionPanel.StyleCache.cs"),Source(root));
}
