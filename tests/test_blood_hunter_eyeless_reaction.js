const assert=require('assert'),fs=require('fs'),vm=require('vm'),path=require('path');
const {runtime,hero,root}=require('./helpers/class_runtime_harness');
const g=runtime(),C=g.DNDClassFeatures,H=g.DNDBloodHunter;
g.Math.random=()=>0.55;
const attacker=hero('Воин',5);attacker.id='attacker';attacker.characterId=attacker.id;
attacker.weapons=[{id:'axe',name:'Топор',damageDice:'1d8',damageType:'slashing',rangeFt:5}];
const hunter=hero(H.CLASS,13,'Орден призрачных убийц');hunter.id='hunter';hunter.characterId=hunter.id;
C.buildFeatureSet(hunter);
assert(C.useFeature(hunter,'chooseBloodCurses',{className:H.CLASS,curses:['eyeless']}).ok);
const initialUses=hunter.resources.bloodMaledict.current;
assert(initialUses>0);
const ctx={source:'attack',attackTotal:12,targetAc:10,natural20:false,amount:5,distanceFt:5,visible:true,returnTarget:{id:'attacker'}};
const option=C.reactionOptions(hunter,ctx);
assert(option&&option.options.some(o=>o.id==='bloodCurseEyeless'),'Eyeless appears in a real attack reaction window');
assert(!C.reactionOptions(hunter,{...ctx,natural20:true})?.options.some(o=>o.id==='bloodCurseEyeless'),'natural twenty is not downgraded');
assert(!C.reactionOptions(hunter,{...ctx,distanceFt:35})?.options.some(o=>o.id==='bloodCurseEyeless'),'cannot react out of range');
assert(!C.reactionOptions(hunter,{...ctx,returnTarget:{id:'attacker',conditionImmunities:['blinded']}})?.options.some(o=>o.id==='bloodCurseEyeless'),'blind-immune attacker cannot be cursed');
const a={id:'attack-actor',characterId:attacker.id,ownerPeerId:'p1',name:'Воин',type:'hero',team:'enemy',hp:45,maxHp:45,ac:10,turnResources:{action:true,bonusAction:true,reaction:true,movement:30}};
const target={id:'defender',characterId:hunter.id,ownerPeerId:'p2',name:'Охотник',type:'hero',team:'party',hp:40,maxHp:40,ac:10,turnResources:{action:true,bonusAction:true,reaction:true,movement:30}};
const tokens={'bt_attack-actor':{x:0,y:0,size:1},bt_defender:{x:1,y:0,size:1}},board={tokens,cols:20,rows:10,cellFt:5};
g.DNDBattleBoard={ensure:()=>board,findToken:k=>tokens[k],distanceFt:(x,y)=>Math.abs(x.x-y.x)*5,lineOfSight:()=>({clear:true,cover:0}),pathCost:()=>5};
g.currentChar={id:'master',initiativeTracker:{round:1,activeIndex:0,combatants:[a,target],battlefield:board}};g.currentCharacter=g.currentChar;
g.autoSaveCurrentCharacter=()=>{};g.renderInitiativeTracker=()=>{};g.dndRenderCombatV3=()=>{};g.dndNetworkGameplayRender=()=>{};
const peers={p1:{profile:attacker},p2:{profile:hunter}},replies=[],requests=[];let handler;
g.dndNetwork={state:{role:'host'},getPeer:id=>peers[id],roster:()=>[],registerActionHandler:fn=>handler=fn,
 sendActionResult:(id,request,result)=>replies.push({id,result}),sendReactionRequest:(id,payload)=>requests.push({id,payload}),commitHostEvent:()=>({seq:1})};
g.addEventListener=(event,fn)=>{if(event==='DOMContentLoaded')fn();};
vm.runInContext(fs.readFileSync(path.join(root,'app/network_gameplay.js'),'utf8'),g,{filename:'app/network_gameplay.js'});
assert(handler);
handler('p1',{type:'ATTACK',requestId:'host-roll',payload:{weaponId:'axe',targetId:'defender',hit:true,damage:999}});
const pending=replies.at(-1).result;
assert(pending.ok&&pending.reactionPending&&pending.hit,JSON.stringify(pending));
assert.strictEqual(target.hp,40,'damage is pending until defender chooses reaction');
assert(requests.length===1&&requests[0].id==='p2');
assert(requests[0].payload.options.some(o=>o.id==='bloodCurseEyeless'));
const reactionId=requests[0].payload.reactionId;
handler('p1',{type:'REACTION_RESPONSE',requestId:'forge',payload:{reactionId,choice:'bloodCurseEyeless'}});
assert.strictEqual(replies.at(-1).result.ok,false,'attacker cannot answer defender reaction');
assert.strictEqual(hunter.resources.bloodMaledict.current,initialUses);
handler('p2',{type:'REACTION_RESPONSE',requestId:'answer',payload:{reactionId,choice:'bloodCurseEyeless'}});
const response=replies.at(-1).result;
assert(response.ok&&response.kind==='reaction_resolved',JSON.stringify(response));
assert(response.reaction&&response.reaction.id==='bloodCurseEyeless'&&response.reaction.attackNegated,'curse turns the true attack into miss: '+JSON.stringify(response));
assert.strictEqual(response.damage.amount,0,'no damage after attack downgraded');
assert.strictEqual(target.hp,40,'defender health must remain unchanged');
assert.strictEqual(hunter.resources.bloodMaledict.current,initialUses-1,'host spends one curse use');
assert.strictEqual(target.turnResources.reaction,false,'reaction consumed on authoritative actor');
handler('p2',{type:'REACTION_RESPONSE',requestId:'duplicate',payload:{reactionId,choice:'bloodCurseEyeless'}});
assert.strictEqual(replies.at(-1).result.ok,false,'reaction cannot be replayed');
assert.strictEqual(hunter.resources.bloodMaledict.current,initialUses-1);
console.log('PASS: Blood Curse of the Eyeless in owner-only pending host attack reaction, real hit cancellation and resources');
