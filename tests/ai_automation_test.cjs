'use strict';
const assert=require('node:assert/strict');
const {developmentGate,releaseGate,cooldown}=require('../tools/ai_automation.cjs');
const approved={paid_api_authorized:true};
const enabled={AI_DEVELOPMENT_ENABLED:'true',AI_ALLOW_PAID_API:'true',OPENAI_API_KEY:'test-placeholder'};
assert.equal(developmentGate({},{}),'disabled');
assert.equal(developmentGate({},{...enabled,AI_ALLOW_PAID_API:''}),'paid-api-not-authorized');
assert.equal(developmentGate(approved,{...enabled,OPENAI_API_KEY:''}),'missing-api-key');
assert.equal(developmentGate({},enabled),'paid-api-not-authorized');
assert.equal(developmentGate(approved,enabled),'ready');
assert.equal(developmentGate({...approved,retry_after:'bad'},enabled),'cooldown');
assert.equal(developmentGate({...approved,retry_after:'2099-01-01'},enabled,0),'cooldown');
assert.equal(developmentGate({...approved,retry_after:'2020-01-01'},enabled,Date.UTC(2026,0,1)),'ready');
assert.equal(cooldown('weekly usage limit',0).retry_after,new Date(7*86400000).toISOString());
assert.equal(cooldown('429 rate limit',0).quota_scope,'hourly');
assert.equal(cooldown('insufficient_quota',0).quota_scope,'billing');
assert(!releaseGate({release_ready:false}));
const ready={release_ready:true,release_source_sha:'a'.repeat(40),release_reason:'finished and checked'};
assert(releaseGate(ready,()=>''));
assert(!releaseGate(ready,args=>args[0]==='diff'?'app/predictor_cards.js':''));
assert(!releaseGate(ready,()=>{throw Error('not ancestor');}));
assert(!releaseGate({...ready,release_source_sha:'HEAD; unsafe'}));
console.log('PASS 16 automation authorization, quota and release-readiness assertions');
