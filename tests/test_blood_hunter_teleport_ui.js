const assert=require('assert'),fs=require('fs'),vm=require('vm'),path=require('path');
const {runtime,hero,root}=require('./helpers/class_runtime_harness');
const g=runtime(),h=hero('Волшебник',9);
h.id='wizard';h.initiativeTracker={activeIndex:0,combatants:[{id:'wizard',ownerPeerId:'p1',name:'Волшебник',type:'hero',hp:40,maxHp:40,speed:30,turnResources:{action:true,bonusAction:true}}]};
h.spellsData=[{name:'Туманный шаг (Misty Step)',level:2,castingClass:'Волшебник',castingTime:'1 бонусное действие'}];
g.currentChar=h;g.currentCharacter=h;
const ids=['dndTurnPlannerModal','dndTurnPlannerActor','dndTurnPlannerTarget','dndTurnPlannerWeapon','dndTurnPlannerSpell','dndTurnPlannerType','dndTurnPlannerSummary'];
const dom=Object.fromEntries(ids.map(id=>[id,{id,value:id==='dndTurnPlannerType'?'CAST_SPELL':'0',style:{},innerHTML:''}]));
g.document.getElementById=id=>dom[id]||null;
g.dndBattleOpen=()=>{};
g.DNDBattleBoard={tokenList:()=>[{id:'bt_wizard',sourceId:'wizard',x:0,y:0,size:1}],setPlanPreview:()=>{},distanceFt:(a,b)=>Math.abs(a.x-b.x)*5,pathCost:(a,b)=>Math.abs(a.x-b.x)*5,lineOfSight:()=>({clear:true,cover:0}),ensure:()=>({cellFt:5})};
const sent=[];g.dndNetwork={state:{role:'player',clientId:'p1'},playerAction:(type,payload)=>sent.push({type,payload})};
vm.runInContext(fs.readFileSync(path.join(root,'app/turn_planner.js'),'utf8'),g,{filename:'app/turn_planner.js'});
assert.equal(typeof g.dndTurnPlannerPickTeleport,'function','map destination selector is exposed');
g.dndTurnPlannerQuick('wizard','','CAST_SPELL');
g.dndTurnPlannerPickTeleport();
g.dndTurnPlannerConfirm();
assert(sent.length===0,'teleport cannot be cast until a destination is selected');
g.dndTurnPlannerPickTeleport();
g.dndTurnPlannerCellSelected({x:2,y:0},null);
g.dndTurnPlannerConfirm();
assert.strictEqual(sent.length,1);
assert.strictEqual(sent[0].type,'CAST_SPELL','teleport is cast immediately, never stored as a prepared action');
assert.strictEqual(sent[0].payload.spellName,'Туманный шаг (Misty Step)');
assert.strictEqual(sent[0].payload.teleportTo.x,2);
assert.strictEqual(sent[0].payload.teleportTo.y,0);
assert.strictEqual(sent[0].payload.hit,undefined);
assert.strictEqual(dom.dndTurnPlannerModal.style.display,'none');
console.log('PASS: grid-selected teleport spell dispatches immediate authenticated CAST_SPELL from player UI');
